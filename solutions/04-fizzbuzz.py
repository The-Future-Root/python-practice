# Solution to 4. FizzBuzz

def fizzbuzz(n):
    """Return the FizzBuzz strings for the numbers 1 to n, as a list."""
    result = []
    for number in range(1, n + 1):
        if number % 15 == 0:
            result.append("FizzBuzz")
        elif number % 3 == 0:
            result.append("Fizz")
        elif number % 5 == 0:
            result.append("Buzz")
        else:
            result.append(str(number))
    return result
